@pytest.mark.parametrize("change,code", [
    (lambda data: data.update(schema_version=2), "INVALID_SNAPSHOT"),
    (lambda data: data.update(horizon_starts_at="2026-11-09T00:00:00Z"), "WRONG_HORIZON"),
    (lambda data: data.update(lecturers=[]), "MISSING_LECTURER"),
    (lambda data: data.update(rosters=[]), "MISSING_ROSTER"),
    (lambda data: roster(data).update(group_number=2), "ROSTER_MISMATCH"),
    (lambda data: roster(data).update(student_ids=[]), "EMPTY_ROSTER"),
    (lambda data: data["rooms"].append(copy.deepcopy(data["rooms"][0])), "DUPLICATE_IDENTITY"),
    (lambda data: data["class_bookings"].append(copy.deepcopy(data["class_bookings"][0])), "DUPLICATE_IDENTITY"),
    (lambda data: data["class_bookings"][0].update(starts_at="2026-11-08T15:30:00"), "INVALID_SNAPSHOT"),
    (lambda data: data["class_bookings"][0].update(duration_minutes=30), "INVALID_SNAPSHOT"),
    (lambda data: pending(data).update(needs_scheduling=False), "STATE_MISMATCH"),
    (lambda data: pending(data).update(timezone="UTC"), "TIMEZONE_MISMATCH"),
    (lambda data: pending(data).update(target_week_start="2026-11-16"), "WRONG_HORIZON"),
    (lambda data: data.update(class_bookings=[]), "BOOKING_MISMATCH"),
    (lambda data: data.update(rooms=[row for row in data["rooms"] if row["id"] != uid(60)]), "MISSING_ROOM"),
    (lambda data: data["class_bookings"][0].update(starts_at="2026-11-08T14:30:00Z", ends_at="2026-11-08T16:00:00Z"), "OUTSIDE_HORIZON"),
])
def test_incomplete_or_inconsistent_database_input_fails_explicitly(provider, change, code):
    _, state = provider
    change(state["payload"])
    with pytest.raises(SchedulingDataError) as error:
        read(provider)
    assert error.value.code == code


