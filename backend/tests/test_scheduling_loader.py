@pytest.fixture
def provider(sql_payload, monkeypatch):
    settings = load_settings()
    settings.supabase.url_env = "SNAPSHOT_TEST_URL"
    settings.supabase.key_env = "SNAPSHOT_TEST_KEY"
    state = {"payload": copy.deepcopy(sql_payload), "calls": [], "status": 200, "body": None, "delay": 0}

    class Handler(BaseHTTPRequestHandler):
        def do_GET(self):
            parsed = urlsplit(self.path)
            params = {key: value[0] for key, value in parse_qs(parsed.query).items()}
            state["calls"].append({"path": parsed.path, "parameters": params, "headers": dict(self.headers)})
            sleep(state["delay"])
            payload = state["payload"]
            table = parsed.path.removeprefix("/rest/v1/")
            source = {
                "teaching_occurrence_details": payload["requirements"],
                "class_session_details": [{key: row[key] for key in
                                           ("id", "section_id", "room_id", "starts_at", "ends_at", "status",
                                            "group_number", "intake_id", "lecturer_id", "duration_minutes")}
                                          for row in payload["class_bookings"]],
                "class_sessions": [{"id": row["id"], "occurrence_id": row["occurrence_id"]}
                                   for row in payload["class_bookings"]],
                "meeting_sessions": [{key: row[key] for key in
                                      ("id", "lecturer_id", "room_id", "starts_at", "ends_at", "status")}
                                     for row in payload["meeting_bookings"]],
                "meeting_students": [{"meeting_id": row["id"], "student_id": student_id}
                                     for row in payload["meeting_bookings"] for student_id in row["student_ids"]],
                "student_intakes": [{"student_id": student_id, "intake_id": row["intake_id"],
                                     "group_number": row["group_number"]}
                                    for row in payload["rosters"] for student_id in row["student_ids"]],
                "rooms": payload["rooms"],
                "lecturers": payload["lecturers"],
            }.get(table, [])

            def matches(row, key, expression):
                if expression.startswith("eq."):
                    return str(row.get(key)) == expression[3:]
                if expression.startswith("in.("):
                    accepted = expression[4:-1].replace('"', "").split(",")
                    return str(row.get(key)) in accepted
                for operator, compare in (("lt.", lambda left, right: left < right),
                                          ("gt.", lambda left, right: left > right)):
                    if expression.startswith(operator):
                        left, right = row.get(key), expression[len(operator):]
                        if key.endswith("_at"):
                            return compare(datetime.fromisoformat(left.replace("Z", "+00:00")),
                                           datetime.fromisoformat(right.replace("Z", "+00:00")))
                        return compare(str(left), right)
                return True

            rows = [row for row in source if all(matches(row, key, value) for key, value in params.items()
                                                  if key not in {"select", "order", "limit", "offset"})]
            order = params.get("order", "")
            if order:
                keys = [item.split(".")[0] for item in order.split(",")]
                rows.sort(key=lambda row: tuple(str(row.get(key)) for key in keys))
            offset, limit = int(params.get("offset", "0")), int(params.get("limit", "500"))
            rows = rows[offset:offset + limit]
            status = state["status"]
            body = state["body"] if state["body"] is not None else json.dumps(rows).encode()
            self.send_response(status)
            self.send_header("Content-Type", "application/json")
            self.end_headers()
            try:
                self.wfile.write(body)
            except (BrokenPipeError, ConnectionResetError, ConnectionAbortedError):
                pass

        def log_message(self, *_):
            pass

    server = ThreadingHTTPServer(("127.0.0.1", 0), Handler)
    thread = Thread(target=server.serve_forever, daemon=True)
    thread.start()
    monkeypatch.setenv(settings.supabase.url_env, f"http://127.0.0.1:{server.server_port}")
    monkeypatch.setenv(settings.supabase.key_env, "sb_secret_snapshot_test")
    yield settings, state
    server.shutdown()
    server.server_close()
    thread.join()


def read(provider, week=date(2026, 11, 9)):
    settings, _ = provider

    async def run():
        async with httpx.AsyncClient(follow_redirects=False) as client:
            return await load_scheduling_snapshot(Supabase(settings.supabase, client), settings.scheduling, week)

    return asyncio.run(run())


def pending(data):
    return next(row for row in data["requirements"] if row["needs_scheduling"])


def roster(data, section=40):
    return next(row for row in data["rosters"] if row["section_id"] == uid(section))


def test_real_postgresql_output_becomes_complete_engine_input_over_http(provider):
    _, state = provider
    snapshot = read(provider)
    assert len(snapshot.requirements) == 2
    assert len(snapshot.pending_requirements) == 1
    lesson = snapshot.pending_requirements[0]
    fixed = next(row for row in snapshot.class_bookings if row.section_id == UUID(int=41))
    assert lesson.student_count == 2
    assert lesson.student_ids == frozenset([UUID(int=10), UUID(int=11)])
    assert lesson.student_ids & fixed.student_ids == {UUID(int=10)}
    assert lesson.intake_id != fixed.intake_id
    assert lesson.lecturer_id != fixed.lecturer_id
    assert len(snapshot.rooms) == 3 and sum(room.is_active for room in snapshot.rooms) == 2
    assert snapshot.meeting_bookings == ()
    assert len(snapshot.opening_windows) == 5
    assert snapshot.opening_windows[0].starts_at.isoformat() == "2026-11-09T00:30:00+00:00"
    assert snapshot.opening_windows[0].ends_at.isoformat() == "2026-11-09T10:00:00+00:00"
    assert any(row.starts_at < snapshot.horizon_starts_at for row in snapshot.class_bookings)
    assert fixed.ends_at - fixed.starts_at == timedelta(minutes=120)
    assert {call["path"] for call in state["calls"]} >= {
        "/rest/v1/teaching_occurrence_details", "/rest/v1/class_session_details",
        "/rest/v1/class_sessions", "/rest/v1/student_intakes", "/rest/v1/rooms", "/rest/v1/lecturers",
    }
    occurrence_query = next(call for call in state["calls"] if call["path"] == "/rest/v1/teaching_occurrence_details")
    assert occurrence_query["parameters"]["target_week_start"] == "eq.2026-11-09"
    assert all(call["path"] != "/rest/v1/rpc/load_scheduling_data" for call in state["calls"])
    assert state["calls"][0]["headers"]["apikey"] == "sb_secret_snapshot_test"
    assert "Authorization" not in state["calls"][0]["headers"]
    assert len(snapshot.revision) == 64
    valid = validate_booking(snapshot, BookingProposal(
        occurrence_id=lesson.occurrence_id, room_id=UUID(int=60), starts_at="2026-11-09T09:17:00+08:00",
    ))
    assert valid.valid
    blocked = validate_booking(snapshot, BookingProposal(
        occurrence_id=lesson.occurrence_id, room_id=UUID(int=60), starts_at="2026-11-09T14:43:00+08:00",
    ))
    assert blocked.reason_codes == ("STUDENT_CONFLICT",)
    assert blocked.issues[0].conflicting_student_count == 1
    candidates = generate_candidates(snapshot, lesson.occurrence_id)
    room_ranges = [item for item in candidates.ranges if item.room_id == UUID(int=60)]
    assert len(room_ranges) == 5
    assert room_ranges[0].latest_start.isoformat() == "2026-11-09T05:13:00+00:00"
    assert any(item.contains(valid.starts_at) for item in room_ranges)
    assert not any(item.contains(blocked.starts_at) for item in room_ranges)
    for item in room_ranges:
        for starts_at in (item.earliest_start, item.latest_start):
            assert validate_booking(snapshot, BookingProposal(
                occurrence_id=lesson.occurrence_id, room_id=item.room_id, starts_at=starts_at,
            )).valid
    solved = solve_weekly_schedule(snapshot, SolverSettings(max_time_seconds=2))
    assert solved.has_solution and solved.required_count == 1
    assert [item.occurrence_id for item in solved.placements] == [lesson.occurrence_id]
    assert solved.placements[0].room_id == UUID(int=60)
    assert solved.snapshot_revision == snapshot.revision
    assert len(state["calls"]) > 1  # Generation uses backend-orchestrated table/view reads.


def test_unique_student_counts_and_input_fingerprint_ignore_order_and_capture_metadata(provider):
    _, state = provider
    first = read(provider)
    state["payload"]["captured_at"] = "2026-11-10T01:00:00Z"
    state["payload"]["database_snapshot"] = "different-read-snapshot"
    for key in ["requirements", "rosters", "rooms", "lecturers", "class_bookings"]:
        state["payload"][key].reverse()
    roster(state["payload"])["student_ids"].append(uid(10))
    second = read(provider)
    assert second.pending_requirements[0].student_count == 2
    assert second.revision == first.revision
    assert second.captured_at != first.captured_at


def test_revision_tracks_room_and_calendar_changes(provider):
    settings, state = provider
    first = read(provider)
    state["payload"]["rooms"][0]["capacity"] += 1
    second = read(provider)
    assert second.revision != first.revision
    settings.scheduling.closed_dates = [date(2026, 11, 10)]
    third = read(provider)
    assert len(third.opening_windows) == 4
    assert third.revision != second.revision
    settings.scheduling.room_compatibility["lecture"] = ("classroom",)
    fourth = read(provider)
    assert fourth.revision != third.revision
    assert next(rule for rule in fourth.room_rules if rule.course_type == "lecture").allowed_room_types == {"classroom"}
    assert next(rule for rule in first.room_rules if rule.course_type == "lecture").allowed_room_types == {"classroom", "auditorium"}


def test_snapshot_is_immutable_and_independent_of_mutable_startup_settings(provider):
    settings, _ = provider
    snapshot = read(provider)
    with pytest.raises(ValidationError):
        snapshot.rooms[0].capacity = 999
    with pytest.raises(AttributeError):
        snapshot.pending_requirements[0].student_ids.add(UUID(int=99))
    settings.scheduling.opening_hours["monday"].opens_at = "11:00"
    assert snapshot.opening_windows[0].starts_at.isoformat() == "2026-11-09T00:30:00+00:00"


